    def fetch_all_cards_by_set(self) -> Dict:
        """Fetch all cards organized by set"""
        print("Fetching cards from all sets...")

        # Get all sets first
        all_sets = self.fetch_all_sets()
        print(f"Found {len(all_sets)} sets")

        cards = {}
        card_count = 0

        # Process each set
        for set_data in all_sets:
            set_code = set_data.get('code')
            set_name = set_data.get('name')
            search_uri = set_data.get('search_uri')

            if not search_uri:
                continue

            print(f"Fetching cards from {set_name} ({set_code})...")

            # Use the search URI to get all cards in the set
            url = search_uri
            set_cards = 0

            while url:
                print(f"  Processing page: {url}")

                # Add delay to avoid rate limiting
                time.sleep(0.1)

                try:
                    response = requests.get(url)

                    # Handle rate limiting with exponential backoff
                    retries = 0
                    while response.status_code == 429 and retries < 5:
                        retry_after = int(response.headers.get('Retry-After', 1))
                        wait_time = retry_after * (2 ** retries)
                        print(f"Rate limited. Waiting {wait_time} seconds...")
                        time.sleep(wait_time)
                        response = requests.get(url)
                        retries += 1

                    if response.status_code != 200:
                        print(f"Error fetching data: {response.status_code}")
                        break

                    data = response.json()

                    # Process cards in this page
                    for card in data.get('data', []):
                        card_id = card.get('id')

                        # Skip cards without IDs
                        if not card_id:
                            continue

                        cards[card_id] = {
                            'id': card_id,
                            'name': card.get('name', ''),
                            'type_line': card.get('type_line', ''),
                            'oracle_text': card.get('oracle_text', ''),
                            'mana_cost': card.get('mana_cost', ''),
                            'cmc': card.get('cmc', 0),
                            'color_identity': card.get('color_identity', []),
                            'keywords': card.get('keywords', []),
                            'image_uris': card.get('image_uris', {}),
                            'legalities': card.get('legalities', {}),
                            'prices': card.get('prices', {}),
                            'rarity': card.get('rarity', '')
                        }
                        set_cards += 1

                    # Check if there's another page
                    url = data.get('next_page')

                except Exception as e:
                    print(f"Error processing set {set_code}: {e}")
                    break

            print(f"  Added {set_cards} cards from {set_name}")
            card_count += set_cards

        self.card_dict = cards
        print(f"Fetched {card_count} cards from {len(all_sets)} sets")

        # Save to Supabase (batched to avoid size limitations)
        if self.use_supabase:
            self._save_cards_to_supabase(cards)

        # Also save locally as backup
        with open(f"{self.data_path}/card_data.json", 'w') as f:
            json.dump(cards, f)

        return cards

    def _save_cards_to_supabase(self, cards: Dict) -> None:
        """Save cards to Supabase in batches"""
        print("Saving cards to Supabase...")

        # Convert dictionary to list for easier batching
        card_list = []
        for card_id, card_data in cards.items():
            # Convert to format for database insertion
            db_card = {
                'id': card_id,
                'name': card_data.get('name', ''),
                'type_line': card_data.get('type_line', ''),
                'oracle_text': card_data.get('oracle_text', ''),
                'mana_cost': card_data.get('mana_cost', ''),
                'cmc': card_data.get('cmc', 0),
                'color_identity': json.dumps(card_data.get('color_identity', [])),
                'keywords': json.dumps(card_data.get('keywords', [])),
                'image_uris': json.dumps(card_data.get('image_uris', {})),
                'legalities': json.dumps(card_data.get('legalities', {})),
                'prices': json.dumps(card_data.get('prices', {})),
                'rarity': card_data.get('rarity', '')
            }
            card_list.append(db_card)

        # Insert in batches of 100
        batch_size = 100
        total_batches = (len(card_list) + batch_size - 1) // batch_size  # Ceiling division

        for i in tqdm(range(0, len(card_list), batch_size), desc="Uploading card batches", total=total_batches):
            batch = card_list[i:i+batch_size]

            try:
                # Upsert data (insert or update if exists)
                result = self.supabase.table('mtg_cards').upsert(batch).execute()

                # Check for errors
                if hasattr(result, 'error') and result.error:
                    print(f"Error in batch {i//batch_size + 1}: {result.error}")
            except Exception as e:
                print(f"Failed to upload batch {i//batch_size + 1}: {e}")

