import json
import os
import time
from tqdm import tqdm
from dotenv import load_dotenv
from supabase import create_client
from google.colab import drive

def process_card_categories():
    """
    Process and save card categories to Supabase:
    - Color identity information
    - Legendary creatures list
    - Price categories

    Uses existing card data without regenerating embeddings.
    """
    print("Starting processing of card categories for Supabase")

    # Mount Google Drive if not already mounted
    try:
        drive.mount('/content/drive', force_remount=False)
        print("Google Drive mounted successfully")
    except:
        print("Google Drive already mounted or could not be mounted")

    # Set data path
    data_path = "/content/drive/MyDrive/MTGData"

    # Load environment variables
    env_path = f"{data_path}/.env"
    if os.path.exists(env_path):
        load_dotenv(env_path)
        print("Loaded environment variables")
    else:
        print("No .env file found. Creating one...")
        os.makedirs(data_path, exist_ok=True)

        # Get Supabase credentials
        from getpass import getpass
        supabase_url = input("Enter your Supabase URL (default: https://hvsbfeyufrzmohzxsbcq.supabase.co): ") or "https://hvsbfeyufrzmohzxsbcq.supabase.co"
        supabase_key = getpass("Enter your Supabase API key: ")

        # Save to .env file
        with open(env_path, 'w') as f:
            f.write(f"SUPABASE_URL={supabase_url}\n")
            f.write(f"SUPABASE_KEY={supabase_key}\n")

        print(f"Created .env file at {env_path}")
        load_dotenv(env_path)

    # Initialize Supabase client
    supabase_url = os.getenv('SUPABASE_URL')
    supabase_key = os.getenv('SUPABASE_KEY')

    if not supabase_key:
        print("ERROR: Supabase key not found in environment variables")
        return

    try:
        supabase = create_client(supabase_url, supabase_key)
        print("Supabase client initialized successfully")
    except Exception as e:
        print(f"Error initializing Supabase: {e}")
        return

    # Load existing card data
    card_data_path = f"{data_path}/card_data.json"
    if not os.path.exists(card_data_path):
        print(f"ERROR: Card data file not found at {card_data_path}")
        print("Please run the full pipeline first to collect card data")
        return

    with open(card_data_path, 'r') as f:
        card_dict = json.load(f)

    print(f"Loaded {len(card_dict)} cards from file")

    # Load price data for price categories
    price_data_path = f"{data_path}/price_data.json"
    if not os.path.exists(price_data_path):
        print(f"WARNING: Price data file not found at {price_data_path}")
        print("Will proceed without price categories")
        price_data = None
    else:
        with open(price_data_path, 'r') as f:
            price_data = json.load(f)
        print(f"Loaded price data for {len(price_data)} cards")

    # Process and save color identity
    def process_and_save_color_identity():
        """Process and save color identity information"""
        print("\n--- Processing Color Identity ---")

        # Extract color identities from card data
        color_identity_dict = {}

        for card_id, card_info in tqdm(card_dict.items(), desc="Extracting color identities"):
            identity = ''.join(sorted(card_info.get('color_identity', [])))
            identity = identity if identity else 'Colorless'

            if identity not in color_identity_dict:
                color_identity_dict[identity] = []
            color_identity_dict[identity].append(card_id)

        print(f"Found {len(color_identity_dict)} different color identities")

        # Save to Supabase
        print("Saving color identity information to Supabase...")

        # Convert to list of records
        color_identity_records = []
        for identity, card_ids in color_identity_dict.items():
            for card_id in card_ids:
                color_identity_records.append({
                    'id': card_id,
                    'color_identity': identity
                })

        try:
            # First clean out old data with a WHERE clause (to satisfy Supabase requirements)
            supabase.table('mtg_color_identity').delete().neq('card_id', 'no-match').execute()
            print("Cleared existing color identity data")

            # Insert in batches
            batch_size = 100
            total_batches = (len(color_identity_records) + batch_size - 1) // batch_size

            for i in tqdm(range(0, len(color_identity_records), batch_size), desc="Uploading color identity records", total=total_batches):
                batch = color_identity_records[i:i+batch_size]
                supabase.table('mtg_color_identity').insert(batch).execute()

            print(f"Saved {len(color_identity_records)} color identity records")
        except Exception as e:
            print(f"Error saving color identity records: {e}")

        return color_identity_dict

    # Process legendary creatures
    def process_and_save_legendary_creatures():
        """Process and save legendary creature information"""
        print("\n--- Processing Legendary Creatures ---")

        # Extract legendary creatures from card data
        legendary_creatures = []

        for card_id, card_info in tqdm(card_dict.items(), desc="Identifying legendary creatures"):
            type_line = card_info.get('type_line', '').lower()
            if 'legendary' in type_line and 'creature' in type_line:
                legendary_creatures.append(card_id)

        print(f"Found {len(legendary_creatures)} legendary creatures")

        # Save to Supabase
        print("Saving legendary creatures to Supabase...")

        # Convert to list of records
        legendary_creature_records = [{'card_id': card_id} for card_id in legendary_creatures]

        try:
            # First clean out old data with a WHERE clause
            supabase.table('mtg_legendary_creatures').delete().neq('card_id', 'no-match').execute()
            print("Cleared existing legendary creatures data")

            # Insert in batches
            batch_size = 100
            total_batches = (len(legendary_creature_records) + batch_size - 1) // batch_size

            for i in tqdm(range(0, len(legendary_creature_records), batch_size), desc="Uploading legendary creatures", total=total_batches):
                batch = legendary_creature_records[i:i+batch_size]
                supabase.table('mtg_legendary_creatures').insert(batch).execute()

            print(f"Saved {len(legendary_creature_records)} legendary creatures")
        except Exception as e:
            print(f"Error saving legendary creatures: {e}")

        return legendary_creatures

    # Process price categories
    def process_and_save_price_categories():
        """Process and save price category information"""
        print("\n--- Processing Price Categories ---")

        if not price_data:
            print("ERROR: Price data not available - skipping price categories")
            return None

        # Function to determine price category
        def determine_price_category(card_id):
            price_info = price_data.get(card_id, {})
            usd_price = 0

            if price_info.get('usd'):
                try:
                    usd_price = float(price_info['usd'])
                except (ValueError, TypeError):
                    usd_price = 0

            if usd_price == 0:
                return 'Unknown'
            elif usd_price < 1:
                return 'Budget'
            elif usd_price < 5:
                return 'Affordable'
            elif usd_price < 20:
                return 'Moderate'
            elif usd_price < 50:
                return 'Premium'
            else:
                return 'High-End'

        # Extract price categories
        price_category_dict = {
            'Unknown': [],
            'Budget': [],
            'Affordable': [],
            'Moderate': [],
            'Premium': [],
            'High-End': []
        }

        for card_id in tqdm(card_dict.keys(), desc="Categorizing card prices"):
            category = determine_price_category(card_id)
            price_category_dict[category].append(card_id)

        # Count cards in each category
        category_counts = {cat: len(cards) for cat, cards in price_category_dict.items()}
        print("Price category distribution:")
        for category, count in category_counts.items():
            print(f"  {category}: {count} cards")

        # Save to Supabase
        print("Saving price categories to Supabase...")

        # Convert to list of records
        price_category_records = []
        for category, card_ids in price_category_dict.items():
            for card_id in card_ids:
                price_category_records.append({
                    'card_id': card_id,
                    'price_category': category
                })

        try:
            # First clean out old data with a WHERE clause
            supabase.table('mtg_price_categories').delete().neq('card_id', 'no-match').execute()
            print("Cleared existing price category data")

            # Insert in batches
            batch_size = 100
            total_batches = (len(price_category_records) + batch_size - 1) // batch_size

            for i in tqdm(range(0, len(price_category_records), batch_size), desc="Uploading price categories", total=total_batches):
                batch = price_category_records[i:i+batch_size]
                supabase.table('mtg_price_categories').insert(batch).execute()

            print(f"Saved {len(price_category_records)} price category records")
        except Exception as e:
            print(f"Error saving price categories: {e}")

        return price_category_dict

    # Main execution flow
    start_time = time.time()

    # Process color identity
    color_identity = process_and_save_color_identity()

    # Process legendary creatures
    legendary_creatures = process_and_save_legendary_creatures()

    # Process price categories
    price_categories = process_and_save_price_categories()

    end_time = time.time()
    elapsed_time = end_time - start_time

    # Print summary
    print("\n--- Processing Summary ---")
    print(f"Processed {len(card_dict)} cards")
    print(f"Processed {len(color_identity)} color identities")
    print(f"Identified {len(legendary_creatures)} legendary creatures")
    if price_categories:
        print(f"Categorized cards into {len(price_categories)} price categories")
    print(f"Total processing time: {elapsed_time:.2f} seconds ({elapsed_time/60:.2f} minutes)")

# Execute the script if run directly
if __name__ == "__main__":
    process_card_categories()