    def _determine_price_category_from_price(self, price: Union[str, float, None]) -> str:
        """Determine price category from a price value"""
        if price is None or price == 'null':
            return 'Unknown'

        # Convert to float if string
        if isinstance(price, str):
            try:
                price = float(price)
            except ValueError:
                return 'Unknown'

        # Categorize
        if price == 0:
            return 'Unknown'
        elif price < 1:
            return 'Budget'
        elif price < 5:
            return 'Affordable'
        elif price < 20:
            return 'Moderate'
        elif price < 50:
            return 'Premium'
        else:
            return 'High-End'

    def get_legendary_creatures(self,
                               color_identity: Optional[str] = None,
                               max_price: Optional[float] = None) -> List[Dict]:
        """Get all legendary creatures with optional filters"""
        results = []

        for card_id, card_info in self.card_dict.items():
            type_line = card_info.get('type_line', '').lower()

            # Skip if not a legendary creature
            if not ('legendary' in type_line and 'creature' in type_line):
                continue

            # Filter by color identity if specified
            if color_identity:
                card_colors = ''.join(sorted(card_info.get('color_identity', [])))
                if color_identity != card_colors:
                    continue

            # Filter by price if specified
            if max_price is not None:
                price_info = self.price_data.get(card_id, {})
                if price_info.get('usd'):
                    try:
                        usd_price = float(price_info['usd'])
                        if usd_price > max_price:
                            continue
                    except (ValueError, TypeError):
                        pass

            # Add to results
            commander_data = {
                'id': card_id,
                'name': card_info.get('name', ''),
                'color_identity': card_info.get('color_identity', []),
                'type_line': card_info.get('type_line', ''),
                'oracle_text': card_info.get('oracle_text', ''),
                'mana_cost': card_info.get('mana_cost', ''),
                'cmc': card_info.get('cmc', 0),
                'image_uri': card_info.get('image_uris', {}).get('small', ''),
                'price_category': self._determine_price_category(card_id),
                'usd_price': self.price_data.get(card_id, {}).get('usd')
            }

            results.append(commander_data)

        # Sort by name
        results.sort(key=lambda x: x['name'])

        return results

