    def categorize_cards(self) -> Dict:
        """Categorize cards by various attributes for easier filtering"""
        print("Categorizing cards...")

        categories = {
            'color_identity': {},
            'creature_types': {},
            'mana_value': {},
            'keywords': {},
            'price_category': {},
            'legendary_creatures': []
        }

        # Extract creature types pattern
        creature_type_pattern = re.compile(r"(Human|Elf|Goblin|Zombie|Dragon|Angel|Demon|Vampire|Merfolk|Beast|Elemental|Wizard|Warrior|Soldier|Rogue|Cleric|Druid|Knight|Artificer|Shaman|Giant|Dinosaur|Spider|Snake|Bird|Cat|Dog|Wolf|Bear|Insect|Fish|Crab|Horror|Spirit|God|Faerie)")

        for card_id, card_info in tqdm(self.card_dict.items()):
            # Categorize by color identity
            identity = ''.join(sorted(card_info.get('color_identity', [])))
            identity = identity if identity else 'Colorless'

            if identity not in categories['color_identity']:
                categories['color_identity'][identity] = []
            categories['color_identity'][identity].append(card_id)

            # Categorize by mana value
            cmc = card_info.get('cmc', 0)
            cmc_category = None

            if cmc == 0: cmc_category = '0'
            elif cmc <= 2: cmc_category = '1-2'
            elif cmc <= 4: cmc_category = '3-4'
            elif cmc <= 6: cmc_category = '5-6'
            else: cmc_category = '7+'

            if cmc_category not in categories['mana_value']:
                categories['mana_value'][cmc_category] = []
            categories['mana_value'][cmc_category].append(card_id)

            # Categorize by keywords
            for keyword in card_info.get('keywords', []):
                if keyword not in categories['keywords']:
                    categories['keywords'][keyword] = []
                categories['keywords'][keyword].append(card_id)

            # Categorize by price
            price_category = self._determine_price_category(card_id)
            if price_category not in categories['price_category']:
                categories['price_category'][price_category] = []
            categories['price_category'][price_category].append(card_id)

            # Check if it's a legendary creature
            type_line = card_info.get('type_line', '').lower()
            if 'legendary' in type_line and 'creature' in type_line:
                categories['legendary_creatures'].append(card_id)

            # Extract creature types
            oracle_text = card_info.get('oracle_text', '')
            type_line = card_info.get('type_line', '')
            combined_text = f"{oracle_text} {type_line}"

            matches = creature_type_pattern.findall(combined_text)
            for creature_type in matches:
                if creature_type not in categories['creature_types']:
                    categories['creature_types'][creature_type] = []
                categories['creature_types'][creature_type].append(card_id)

        # Save to Supabase
        if self.use_supabase:
            self._save_categories_to_supabase(categories)

        # Save locally as well
        with open(f"{self.data_path}/card_categories.json", 'w') as f:
            json.dump(categories, f)

        return categories

