    def search_cards_by_embeddings(self, query_text: str, n: int = 10,
                                  price_filter: Optional[str] = None) -> List[Dict]:
        """Search for cards similar to the query text with optional price filtering"""
        # Encode the query
        query_embedding = self.model.encode([query_text])

        # Calculate similarities
        similarities = {}
        for card_id, embedding in self.embeddings.items():
            # Skip if price filter is active and card doesn't match
            if price_filter and self._determine_price_category(card_id) != price_filter:
                continue

            # Calculate cosine similarity
            similarity = np.dot(query_embedding, embedding) / (
                np.linalg.norm(query_embedding) * np.linalg.norm(embedding)
            )
            similarities[card_id] = similarity

        # Sort by similarity and get top n
        top_cards = sorted(similarities.items(), key=lambda x: x[1], reverse=True)[:n]

        # Return full card data
        results = []
        for card_id, similarity in top_cards:
            card_data = self.card_dict[card_id].copy()
            card_data['similarity'] = similarity
            card_data['price_category'] = self._determine_price_category(card_id)

            # Add actual price
            price_info = self.price_data.get(card_id, {})
            card_data['usd_price'] = price_info.get('usd')

            results.append(card_data)

        return results

