    def get_image_urls_for_deck_generator(self):
        """Extract image URLs by card name for use in deck visualization"""
        card_images = {}

        for card_id, card_info in self.card_dict.items():
            card_name = card_info.get('name')
            if not card_name:
                continue

            # Handle dual-faced cards
            if 'card_faces' in card_info and 'image_uris' not in card_info:
                # Use front face image
                image_url = card_info.get('card_faces', [{}])[0].get('image_uris', {}).get('normal')
            else:
                # Get the normal image URL
                image_url = card_info.get('image_uris', {}).get('normal')

            if image_url:
                card_images[card_name] = image_url

        # Save to disk for efficient future use
        with open(f"{self.data_path}/card_images.json", 'w') as f:
            json.dump(card_images, f)

        # Save to Supabase if enabled
        if self.use_supabase:
            self._save_card_images_to_supabase(card_images)

        return card_images

    def _save_card_images_to_supabase(self, card_images: Dict) -> None:
        """Save card images to Supabase"""
        print("Saving card images to Supabase...")

        # Convert dictionary to list
        image_list = []
        for card_name, image_url in card_images.items():
            db_image = {
                'card_name': card_name,
                'image_url': image_url,
                'updated_at': time.strftime('%Y-%m-%d %H:%M:%S')
            }
            image_list.append(db_image)

        # Insert in batches
        batch_size = 100
        total_batches = (len(image_list) + batch_size - 1) // batch_size

        for i in tqdm(range(0, len(image_list), batch_size), desc="Uploading image URL batches", total=total_batches):
            batch = image_list[i:i+batch_size]

            try:
                # Upsert data
                result = self.supabase.table('mtg_card_images').upsert(batch).execute()

                if hasattr(result, 'error') and result.error:
                    print(f"Error in batch {i//batch_size + 1}: {result.error}")
            except Exception as e:
                print(f"Failed to upload image URL batch {i//batch_size + 1}: {e}")

