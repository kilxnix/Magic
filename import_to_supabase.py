    def prepare_text_for_embedding(self, card_info: Dict) -> str:
        """Prepare card text for embedding by combining relevant fields"""
        text_parts = []

        # Add card name
        text_parts.append(f"Name: {card_info.get('name', '')}")

        # Add mana cost if available
        if 'mana_cost' in card_info and card_info['mana_cost']:
            text_parts.append(f"Mana Cost: {card_info['mana_cost']}")

        # Add type line
        if 'type_line' in card_info and card_info['type_line']:
            text_parts.append(f"Type: {card_info['type_line']}")

        # Add oracle text
        if 'oracle_text' in card_info and card_info['oracle_text']:
            text_parts.append(f"Text: {card_info['oracle_text']}")

        # Add keywords
        if 'keywords' in card_info and card_info['keywords']:
            text_parts.append(f"Keywords: {', '.join(card_info['keywords'])}")

        # Add color identity
        if 'color_identity' in card_info and card_info['color_identity']:
            text_parts.append(f"Colors: {', '.join(card_info['color_identity'])}")

        return " ".join(text_parts)

    def create_card_embeddings(self) -> Dict:
        """Create vector embeddings for all cards based on their text"""
        print("Creating card embeddings...")

        embeddings = {}

        # Prepare the text for all cards
        texts = []
        card_ids = []

        for card_id, card_info in tqdm(self.card_dict.items(), desc="Preparing texts"):
            card_text = self.prepare_text_for_embedding(card_info)
            texts.append(card_text)
            card_ids.append(card_id)

        # Create embeddings in batches to avoid OOM errors in Colab
        batch_size = 64  # Smaller batch size for Colab
        for i in tqdm(range(0, len(texts), batch_size), desc="Generating embeddings"):
            batch_texts = texts[i:i+batch_size]
            batch_ids = card_ids[i:i+batch_size]

            # Generate embeddings
            batch_embeddings = self.model.encode(batch_texts)

            # Store embeddings
            for j, card_id in enumerate(batch_ids):
                embeddings[card_id] = batch_embeddings[j]

        self.embeddings = embeddings

        # Save to Supabase
        if self.use_supabase:
            self._save_card_embeddings_to_supabase(embeddings)

        # Save locally as well
        with open(f"{self.data_path}/card_embeddings.pkl", 'wb') as f:
            pickle.dump(embeddings, f)

        return embeddings

