    def create_price_embeddings(self) -> Dict:
        """Create vector embeddings specifically for price ranges"""
        print("Creating price embeddings...")

        price_embeddings = {}

        # Define price ranges for vectorization
        price_ranges = [
            (0, 0),       # Unknown/Zero
            (0.01, 1),    # Budget
            (1, 5),       # Affordable
            (5, 20),      # Moderate
            (20, 50),     # Premium
            (50, 1000)    # High-end
        ]

        embedding_dim = len(price_ranges)

        for card_id, price_info in tqdm(self.price_data.items()):
            # Get USD price (or default to 0)
            usd_price = 0
            if price_info['usd']:
                try:
                    usd_price = float(price_info['usd'])
                except (ValueError, TypeError):
                    usd_price = 0

            # Create a one-hot encoding based on price range
            embedding = np.zeros(embedding_dim)

            for i, (min_price, max_price) in enumerate(price_ranges):
                if min_price <= usd_price <= max_price:
                    embedding[i] = 1
                    break

            price_embeddings[card_id] = embedding

        self.price_embeddings = price_embeddings

        # Save to Supabase
        if self.use_supabase:
            self._save_price_embeddings_to_supabase(price_embeddings)

        # Save locally as well
        with open(f"{self.data_path}/price_embeddings.pkl", 'wb') as f:
            pickle.dump(price_embeddings, f)

        return price_embeddings

